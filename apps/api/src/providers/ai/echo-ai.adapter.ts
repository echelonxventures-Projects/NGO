import { Injectable, Logger } from '@nestjs/common';
import { AiCompletionInput, AiCompletionResult, AiPort } from './ai.port';

/**
 * Free-first, offline, deterministic AI adapter. It requires no API key and no network, so
 * the platform's AI features always run (CI, local dev, air-gapped deployments). It produces
 * structured, useful-but-templated responses derived from the prompt rather than a real LLM.
 * Swap AI_PROVIDER to `ollama` (local) or a hosted provider for genuine generation.
 */
@Injectable()
export class EchoAiAdapter implements AiPort {
  readonly name = 'echo';
  private readonly logger = new Logger(EchoAiAdapter.name);

  async complete(input: AiCompletionInput): Promise<AiCompletionResult> {
    const system = input.messages.find((m) => m.role === 'system')?.content ?? '';
    const lastUser = [...input.messages].reverse().find((m) => m.role === 'user')?.content ?? '';

    const text = this.synthesize(system, lastUser);
    this.logger.debug(`echo completion (${text.length} chars)`);

    return {
      provider: this.name,
      model: 'echo-1',
      text,
      usage: {
        promptTokens: this.approxTokens(input.messages.map((m) => m.content).join(' ')),
        completionTokens: this.approxTokens(text),
      },
    };
  }

  /**
   * Deterministic synthesis: echoes the instruction context and produces a lightly
   * structured answer so downstream parsing (e.g. JSON-mode features) still has something
   * to work with. JSON is emitted when the system prompt asks for it.
   */
  private synthesize(system: string, user: string): string {
    const wantsJson = /json/i.test(system);
    const topic = user.slice(0, 280).trim() || 'the requested topic';

    if (wantsJson) {
      // Best-effort: return a minimal valid JSON object echoing the topic.
      return JSON.stringify({
        note: 'echo provider — deterministic placeholder output',
        topic,
        items: [],
      });
    }

    return [
      `Here is an AI-generated response about: ${topic}`,
      '',
      '1. Key idea — a concise framing of the topic.',
      '2. Why it matters — practical relevance for the reader.',
      '3. Next step — a concrete action to apply this.',
      '',
      '(Generated by the free-first "echo" AI provider. Configure AI_PROVIDER=ollama or a',
      'hosted provider for full large-language-model responses.)',
    ].join('\n');
  }

  private approxTokens(s: string): number {
    return Math.ceil(s.length / 4);
  }
}
